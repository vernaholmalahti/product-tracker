import { Router } from "express";
import { z } from "zod";
import { prisma } from "../db/client";

export const deviceRoutes = Router();

// What the app must send. zod checks the shape at runtime – TypeScript types alone
// can't, because the request body comes from outside our code.
const registerDeviceBody = z.object({
  id: z.uuid(), // generated by the app on first start
  // Sent once the user allows notifications. Format: ExponentPushToken[...]
  expoPushToken: z.string().regex(/^ExponentPushToken\[.+\]$/).optional(),
});

// POST /devices – register an anonymous device (no login, no personal data).
// Safe to call on every app start: creates the device once, then does nothing.
deviceRoutes.post("/devices", async (req, res) => {
  const parsed = registerDeviceBody.safeParse(req.body);
  if (!parsed.success) {
    res.status(400).json({ error: "Body must be { id: <uuid>, expoPushToken?: ExponentPushToken[...] }" });
    return;
  }

  const { id, expoPushToken } = parsed.data;
  await prisma.device.upsert({
    where: { id },
    // Already registered: only save the token if one was sent (tokens can change).
    update: expoPushToken ? { expoPushToken } : {},
    create: { id, expoPushToken },
  });
  res.status(204).end(); // 204 = success, no content to send back
});
